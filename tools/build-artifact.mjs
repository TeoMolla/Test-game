/**
 * tools/build-artifact.mjs — Flatten the game into ONE self-contained HTML file.
 *
 * The prototype is deliberately buildless: it runs from source as ES modules
 * over any static server. This script exists only to produce a single-file
 * copy for places that can host exactly one HTML document (a published
 * artifact, an email attachment, an AirDrop to a phone). The source of truth
 * is always src/ — never hand-edit the output.
 *
 *   node tools/build-artifact.mjs [outFile]
 *
 * How it works: modules are concatenated in dependency order into one scope
 * with their import/export keywords stripped. Two wrinkles are handled
 * explicitly:
 *   - `import * as inventory` becomes a literal namespace object.
 *   - Every screen module exports `render`, so screens are each wrapped in an
 *     IIFE. They reference app.js's `navigate`/`refresh`, which are function
 *     declarations and therefore hoisted above them in the flattened scope —
 *     the same lazy resolution the real ESM cycle relies on.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = process.argv[2] || resolve(root, 'dist/z-fighters.html');

/** Dependency order. Every module appears after everything it imports. */
const MODULES = [
  'src/config.js',
  'src/hero/heroes.js',
  'src/skills/skills.js',
  'src/gear/gear.js',
  'src/progression/enemies.js',
  'src/progression/stages.js',
  'src/progression/dungeons.js',
  'src/save/index.js',
  'src/gear/index.js',
  'src/inventory/index.js',
  'src/skills/index.js',
  'src/hero/index.js',
  'src/progression/index.js',
  'src/battle/targeting.js',
  'src/battle/engine.js',
  'src/battle/index.js',
  'src/ui/dom.js',
  'src/ui/avatar.js',
  'src/ui/sprites.js',
  'src/ui/spriteAnimator.js',
];

const SCREENS = [
  'campaign', 'dungeons', 'roster', 'companions', 'bag',
  'heroDetail', 'formation', 'battle', 'results',
];

/** Modules imported elsewhere as `import * as name` need a real namespace object. */
const NAMESPACES = { inventory: 'src/inventory/index.js' };

const read = (rel) => readFileSync(resolve(root, rel), 'utf8');

/**
 * A published artifact supplies its own <head>, so this file cannot declare a
 * charset — a <meta charset> inside <body> comes too late for the parser.
 * Rather than gamble on the host's declaration, the output is escaped to pure
 * ASCII, per context, which makes the document's encoding irrelevant.
 */
const NON_ASCII = /[^\x00-\x7F]/gu;   // the `u` flag matches astral chars whole

const jsAscii = (s) => s.replace(NON_ASCII, (ch) => {
  let out = '';
  for (let i = 0; i < ch.length; i++) {           // surrogate pairs -> two escapes
    out += '\\u' + ch.charCodeAt(i).toString(16).padStart(4, '0');
  }
  return out;
});

// CSS escapes take 1-6 hex digits; always emitting 6 removes the need for a
// terminating space.
const cssAscii = (s) => s.replace(NON_ASCII, (ch) => '\\' + ch.codePointAt(0).toString(16).padStart(6, '0'));

const htmlAscii = (s) => s.replace(NON_ASCII, (ch) => '&#x' + ch.codePointAt(0).toString(16) + ';');



/** Strip ESM syntax, leaving plain top-level declarations. */
function strip(src) {
  return src
    .replace(/^import[\s\S]*?from\s*['"][^'"]+['"]\s*;/gm, '')   // import ... from '...'
    .replace(/^import\s*['"][^'"]+['"]\s*;/gm, '')               // bare import
    .replace(/^export\s*\{[^}]*\}\s*;/gm, '')                    // re-exports (already defined)
    .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm, '')
    .trim();
}

/** Top-level names a module exports, so a screen IIFE can return them. */
function exportedNames(src) {
  const names = [];
  const re = /^export\s+(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(src))) names.push(m[1]);
  return names;
}

const parts = [];
parts.push('/* Z-Fighters — generated by tools/build-artifact.mjs. Edit src/, not this. */');

for (const rel of MODULES) {
  const src = read(rel);
  parts.push(`\n/* ===== ${rel} ===== */\n${strip(src)}`);

  for (const [ns, owner] of Object.entries(NAMESPACES)) {
    if (owner !== rel) continue;
    const names = exportedNames(src);
    if (!names.length) throw new Error(`namespace ${ns}: no exports found in ${rel}`);
    parts.push(`const ${ns} = { ${names.join(', ')} };`);
  }
}

for (const name of SCREENS) {
  const rel = `src/ui/screens/${name}.js`;
  const src = read(rel);
  const names = exportedNames(src);
  if (!names.includes('render')) throw new Error(`${rel} does not export render()`);
  parts.push(`\n/* ===== ${rel} ===== */\nconst __screen_${name} = (() => {\n${strip(src)}\nreturn { ${names.join(', ')} };\n})();`);
}

// app.js resolves its screen registry against the wrapped screens.
let app = strip(read('src/ui/app.js'));
const registry = SCREENS.map((n) => `${n}: __screen_${n}`).join(', ');
const before = app;
app = app.replace(
  /const SCREENS = \{[^}]*\};/,
  `const SCREENS = { ${registry} };`
);
if (app === before) throw new Error('could not rewrite the SCREENS registry in ui/app.js');
parts.push(`\n/* ===== src/ui/app.js ===== */\n${app}`);

parts.push(`\n/* ===== src/main.js ===== */\n${strip(read('src/main.js'))}`);

let js = parts.join('\n');

// Sprite art has to travel inside the file too. Every asset is referenced as a
// literal 'assets/...' string (see ui/sprites.js), so one pass catches them all.
const MIME = { png: 'image/png', jpg: 'image/jpeg', webp: 'image/webp' };
let inlined = 0;
js = js.replace(/'(assets\/[^']+\.(png|jpg|webp))'/g, (_m, rel, ext) => {
  const buf = readFileSync(resolve(root, rel));   // throws if the asset is missing
  inlined += 1;
  return `'data:${MIME[ext]};base64,${buf.toString('base64')}'`;
});
if (!inlined) throw new Error('no sprite assets were inlined — did the asset paths change?');
console.log(`inlined ${inlined} sprite assets`);
js = jsAscii(js);

// Sanity: nothing ESM should survive into the flattened scope.
for (const bad of [/^import\s/m, /^export\s/m]) {
  if (bad.test(js)) throw new Error(`leftover ESM syntax matching ${bad}`);
}

let css = [read('styles/main.css'), read('styles/battle.css')].join('\n\n');

// The vendored webfont has to travel inside the file — the artifact is a single
// document with nowhere to put a sibling asset.
const fontRef = "url('../assets/anton-latin.woff2') format('woff2')";
if (!css.includes(fontRef)) throw new Error('font @font-face src not found in the CSS');
const fontB64 = readFileSync(resolve(root, 'assets/anton-latin.woff2')).toString('base64');
css = cssAscii(css.replace(fontRef, `url(data:font/woff2;base64,${fontB64}) format('woff2')`));

// Artifact pages are published as page content: the host supplies the
// doctype/html/head/body wrapper, so none of those tags appear here.
const html = `<title>Z-Fighters</title>
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<meta name="theme-color" content="#0b1020">
<style>
${css}
</style>

<div id="app">
  <header id="topbar">
    <button class="back-btn" data-action="back" aria-label="Back" hidden>&lsaquo;</button>
    <div class="screen-title" id="screen-title">Campaign</div>
    <div class="wallet">
      <span class="wallet-chip" id="wallet-senzu"><span class="ico">&#129747;</span><span class="val">0</span></span>
      <span class="wallet-chip" id="wallet-zeni"><span class="ico">&#128176;</span><span class="val">0</span></span>
    </div>
  </header>

  <main id="screen" aria-live="polite"></main>

  <nav id="tabbar">
    <button class="tab" data-tab="campaign"><span class="ico">&#128506;&#65039;</span><span>Campaign</span></button>
    <button class="tab" data-tab="dungeons"><span class="ico">&#127744;</span><span>Dungeons</span></button>
    <button class="tab" data-tab="roster"><span class="ico">&#128293;</span><span>Hero</span></button>
    <button class="tab" data-tab="companions"><span class="ico">&#128101;</span><span>Companions</span></button>
    <button class="tab" data-tab="bag"><span class="ico">&#127890;</span><span>Bag</span></button>
  </nav>
</div>

<div id="toasts"></div>

<script type="module">
${js}
</script>
`;

const ascii = htmlAscii(html);
const stray = ascii.match(NON_ASCII);
if (stray) throw new Error(`output is not pure ASCII: ${stray.slice(0, 5).join(' ')}`);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ascii, 'ascii');
console.log(`wrote ${outFile}  (${(ascii.length / 1024).toFixed(1)} KB, ASCII-only)`);
